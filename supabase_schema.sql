-- ========================================================
-- SKEMA TABEL WISHES UNTUK SUPABASE
-- Salin dan tempel seluruh isi script ini ke:
-- Supabase Dashboard -> Menu "SQL Editor" -> Klik "New query" -> Run
-- ========================================================

-- 1. Buat tabel wishes jika belum ada
CREATE TABLE IF NOT EXISTS public.wishes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  message TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Aktifkan Row Level Security (RLS) demi keamanan
ALTER TABLE public.wishes ENABLE ROW LEVEL SECURITY;

-- 3. Hapus policy lama jika pernah dibuat (agar tidak duplikat)
DROP POLICY IF EXISTS "Izinkan Siapa Saja Membaca Ucapan" ON public.wishes;
DROP POLICY IF EXISTS "Izinkan Siapa Saja Mengirim Ucapan" ON public.wishes;

-- 4. Buat Policy agar pengunjung publik dapat membaca ucapan
CREATE POLICY "Izinkan Siapa Saja Membaca Ucapan"
ON public.wishes
FOR SELECT
TO anon, authenticated
USING (true);

-- 5. Buat Policy agar pengunjung publik dapat mengirimkan ucapan baru
CREATE POLICY "Izinkan Siapa Saja Mengirim Ucapan"
ON public.wishes
FOR INSERT
TO anon, authenticated
WITH CHECK (true);

-- 6. Masukkan ucapan awal sebagai contoh
INSERT INTO public.wishes (name, message, created_at)
VALUES ('Ali', 'Selamat ulang tahun cantik!', '2026-11-14T13:21:00.678Z')
ON CONFLICT DO NOTHING;
